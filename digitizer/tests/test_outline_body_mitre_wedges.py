def _kw():
    return dict(angle_deg=None, row_mm=0.4, stitch_mm=3.5, underlay_style="none", trim_at_mm=2.0)


@pytest.mark.parametrize("poly", [WEDGE, LIGHTHOUSE_SF240], ids=["synthetic", "lighthouse"])
def test_the_mitre_buffer_really_shatters(poly):
    # the precondition: without the fix this is what reached stitch_shape
    raw = poly.buffer(PULL_MM, join_style=2)
    assert poly.is_valid and poly.geom_type == "Polygon"
    assert raw.geom_type == "MultiPolygon"
    with pytest.raises(AttributeError, match="exterior"):
        stitch_shape(raw, "S", **_kw())


@pytest.mark.parametrize("poly", [WEDGE, LIGHTHOUSE_SF240], ids=["synthetic", "lighthouse"])
def test_grown_body_is_one_polygon_holding_all_the_artwork(poly):
    raw = poly.buffer(PULL_MM, join_style=2)
    body = grown_body(poly, PULL_MM)
    assert body.geom_type == "Polygon"
    assert body.contains(poly)
    assert body.area == max(g.area for g in raw.geoms)
    # what was left behind is wedge, not artwork
    assert sum(g.area for g in raw.geoms) - body.area < 0.01 * body.area
    runs, report = stitch_shape(body, "S", **_kw())
    assert runs and not report["empty"]


def test_a_buffer_that_stays_whole_is_returned_unchanged():
    poly = box(0, 0, 10, 4)
    assert grown_body(poly, PULL_MM).equals_exact(poly.buffer(PULL_MM, join_style=2), 0)
