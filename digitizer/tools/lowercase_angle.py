def make_fixture(base: Path = FIXTURE) -> None:
    """Draw the fixture and its glyph boxes (deterministic for one Pillow)."""
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.load_default(size=FONT_SIZE)
    width = int(max(font.getlength(t) for t in LINES)) + 2 * MARGIN
    height = LINE_STEP * len(LINES) + 2 * MARGIN
    img = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(img)
    glyphs = []
    for li, text in enumerate(LINES):
        y = MARGIN + li * LINE_STEP
        draw.text((MARGIN, y), text, font=font, fill="black")
        for i, ch in enumerate(text):
            x = MARGIN + font.getlength(text[:i])
            bb = font.getbbox(ch)
            glyphs.append(dict(ch=ch, line=li,
                               box=[x + bb[0], y + bb[1], x + bb[2], y + bb[3]]))
    ascent = font.getmetrics()[0]
    meta = dict(font="Aileron Regular (Pillow ImageFont.load_default, CC0)",
                size=FONT_SIZE, lines=list(LINES), image=[width, height],
                baselines=[MARGIN + li * LINE_STEP + ascent for li in range(len(LINES))],
                glyphs=glyphs)
    img.save(base.with_suffix(".png"))
    base.with_suffix(".json").write_text(json.dumps(meta, indent=1) + "\n", encoding="utf-8")


def _fold(a):
    return np.abs((np.asarray(a, dtype=float) + 90.0) % 180.0 - 90.0)


def target_lean(own_perp_deg, house_deg):
    """The rule's lean for a cross whose column's own perpendicular is
    `own_perp_deg`, under house angle `house_deg` (`satin_house_fourfold`'s
    fade): held at the house (lean d) up to the cap, then
    cap * (90 - d) / (90 - cap), 0 at 90."""
    d = _fold(np.asarray(own_perp_deg, dtype=float) - house_deg)
    return np.where(d <= LEAN_CAP_DEG, d, LEAN_CAP_DEG * (90.0 - d) / (90.0 - LEAN_CAP_DEG))


def cross_records(plan, shape_ids):
    """-> list of dicts per satin cross of `shape_ids`: mid (mm), cross and
    advance angle (deg), lean off own perpendicular, pitch to the next cross."""
    from digitizer_core.stage6_satin import strip_splits
    from digitizer_core.stitches import strip_ties
    out = []
    for _block, run in plan.iter_runs():
        if run.kind != "satin" or run.shape_id not in shape_ids:
            continue
        pts = np.asarray(strip_splits(strip_ties(list(run.points))), dtype=float)
        if len(pts) < 6:
            continue
        vec = pts[1:] - pts[:-1]
        length = np.hypot(vec[:, 0], vec[:, 1])
        idx = np.nonzero(length > 0.6)[0]
        if len(idx) < 5:
            continue
        mids = (pts[idx] + pts[idx + 1]) / 2.0
        cross = np.degrees(np.arctan2(vec[idx, 1], vec[idx, 0]))
        adv = np.degrees(np.arctan2(mids[2:, 1] - mids[:-2, 1], mids[2:, 0] - mids[:-2, 0]))
        unit = vec[idx] / length[idx][:, None]
        normal = np.stack([-unit[:, 1], unit[:, 0]], axis=1)
        gaps = np.abs(np.einsum("ij,ij->i", mids[1:] - mids[:-1], normal[:-1]))
        # The STATION cross. Both engines lay the flat zigzag A1 B1 A2 B2
        # (`columns._satin_points`, `satin_stroke`): the EVEN legs are the
        # rail-to-rail crosses the construction chose, the odd legs the
        # return to the next station, which leans atan(spacing / width) by
        # geometry alone -- 17 deg on a 1.3 mm stem at 0.4 mm, more on a
        # thin bowl or round a tight curve. `lean` reads both legs (the
        # 2026-09-03 instrument's figure); `station_lean` reads only the
        # even legs, against the advance between neighbouring STATIONS.
        sta = [k for k in range(len(idx)) if idx[k] % 2 == 0]
        st_lean = {}
        for j in range(1, len(sta) - 1):
            a, b = mids[sta[j - 1]], mids[sta[j + 1]]
            st_adv = np.degrees(np.arctan2(b[1] - a[1], b[0] - a[0]))
            st_lean[sta[j]] = float(_fold(cross[sta[j]] - (st_adv + 90.0)))
        # arc length of the cross midpoints along the run, for "how far from
        # the end of its column" (a junction mitre or a free end fans there)
        arc = np.concatenate([[0.0], np.cumsum(np.hypot(*(mids[1:] - mids[:-1]).T))])
        for k in range(1, len(idx) - 1):
            out.append(dict(shape=run.shape_id, x=float(mids[k, 0]), y=float(mids[k, 1]),
                            cross=float(cross[k]), advance=float(adv[k - 1]),
                            lean=float(_fold(cross[k] - (adv[k - 1] + 90.0))),
                            station_lean=st_lean.get(k),
                            width=float(length[idx[k]]),
                            end_mm=float(min(arc[k], arc[-1] - arc[k])),
                            pitch=float(gaps[k]) if 0.1 < gaps[k] < 1.0 else None))
    return out


SHORT_FRAC = 0.5    # a satin leg under this share of its run's median leg is short


def junction_short_crosses(plan, shape_ids):
    """-> [(x, y, length mm)], one per SHORT satin leg at a JUNCTION: under
    SHORT_FRAC of its own run's median leg, its midpoint within that median
    of another satin run of the same shape (where two columns meet). The
    knot #887's u traded its shoulder fold for -- a spur cut off its stem,
    sewn as a fan of short crosses beside the stem and the bowl -- reads
    here, which no lean figure does: the crosses there are short, not
    leaning. Splits and ties are stripped first, as in `cross_records`."""
    from shapely.geometry import LineString, Point
    from digitizer_core.stage6_satin import strip_splits
    from digitizer_core.stitches import strip_ties
    runs = {}
    for _block, run in plan.iter_runs():
        if run.kind != "satin" or run.shape_id not in shape_ids:
            continue
        pts = np.asarray(strip_splits(strip_ties(list(run.points))), dtype=float)
        if len(pts) >= 4:
            runs.setdefault(run.shape_id, []).append(pts)
    out = []
    for rl in runs.values():
        lines = [LineString(p) for p in rl]
        for k, pts in enumerate(rl):
            others = [ln for j, ln in enumerate(lines) if j != k]
            if not others:
                continue
            vec = pts[1:] - pts[:-1]
            length = np.hypot(vec[:, 0], vec[:, 1])
            real = length > 0.05
            if not real.any():
                continue
            med = float(np.median(length[real]))
            for i in np.nonzero(real & (length < SHORT_FRAC * med))[0]:
                m = (pts[i] + pts[i + 1]) / 2.0
                if min(o.distance(Point(m)) for o in others) < med:
                    out.append((float(m[0]), float(m[1]), float(length[i])))
    return out


def part_of(advance_deg: float, line_deg: float = 0.0) -> str:
    a = float(_fold(advance_deg - line_deg))
    if a >= STEM_DEG:
        return "stem"
    if a <= BAR_DEG:
        return "bar"
    return "slant"


def mm_to_px(result, image_wh):
    """mm -> source-image px: the design's mm origin is the centre of
    `art_box_frac`, scaled by the box's width over the design's."""
    w, h = image_wh
    x0, y0, x1, y1 = result.art_box_frac
    s = (x1 - x0) * w / result.design_size_mm[0]
    cx, cy = (x0 + x1) / 2.0 * w, (y0 + y1) / 2.0 * h
    return lambda x, y: (cx + x * s, cy + y * s), s


def summarize(recs, house_deg: float) -> dict:
    if not recs:
        return dict(n=0)
    lean = np.array([r["lean"] for r in recs])
    pitch = [r["pitch"] for r in recs if r["pitch"] is not None]
    st = [r for r in recs if r["station_lean"] is not None] or recs
    station = np.array([r["station_lean"] if r["station_lean"] is not None else r["lean"]
                        for r in st])
    # the rule's target and the house reading, per STATION cross
    tgt = target_lean(np.array([r["advance"] + 90.0 for r in st]), house_deg)
    vs_house = _fold(np.array([r["cross"] for r in st]) - house_deg)
    return dict(n=len(recs), lean_p50=float(np.median(lean)),
                lean_p90=float(np.percentile(lean, 90)),
                past45=float(np.mean(lean > 45.0)),
                stations=len(st),
                station_p50=float(np.median(station)),
                station_p90=float(np.percentile(station, 90)),
                station_past45=float(np.mean(station > 45.0)),
                width_p50=float(np.median([r["width"] for r in recs])),
                # share of the >45 crosses within one column width of their
                # run's end: the end/junction fan, not the column's middle
                past45_at_end=(float(np.mean([r["end_mm"] <= r["width"] for r in recs
                                              if r["lean"] > 45.0]))
                               if np.any(lean > 45.0) else None),
                at_end=float(np.mean([r["end_mm"] <= r["width"] for r in recs])),
                target_p50=float(np.median(tgt)),
                dev_p50=float(np.median(np.abs(station - tgt))),
                vs_house_p50=float(np.median(vs_house)),
                pitch_p50=float(np.median(pitch)) if pitch else None)


def _glyph_at(meta, px, py):
    best, bd = None, 1e9
    for g in meta["glyphs"]:
        x0, y0, x1, y1 = g["box"]
        if x0 - 4 <= px <= x1 + 4 and y0 - 4 <= py <= y1 + 4:
            d = abs(px - (x0 + x1) / 2.0)
            if d < bd:
                best, bd = g, d
    return best


def measure_synthetic(width_mm: float, columns: bool = True, base: Path = FIXTURE,
                      fold_cuts: bool = False):
    """-> (report dict, result, plan) for the fixture at `width_mm`.
    `fold_cuts` digitizes with `cfg.lettering_columns_fold_cuts`."""
    from digitizer_core import PipelineConfig, digitize
    from digitizer_core.columns import is_lettering
    meta = json.loads(base.with_suffix(".json").read_text(encoding="utf-8"))
    cfg = PipelineConfig(target_width_mm=width_mm, forced_class="flat",
                         lettering_columns=columns,
                         **({"lettering_columns_fold_cuts": True} if fold_cuts else {}))
    result, plan = digitize(base.with_suffix(".png"), cfg)
    to_px, s = mm_to_px(result, meta["image"])
    letters = {r.shape_id: r for r in result.regions if is_lettering(r, cfg)}
    houses = {r.meta.get("satin_angle_deg") for r in letters.values()}
    house = next(iter(houses)) if len(houses) == 1 else 0.0
    house = 0.0 if house is None else float(house)
    recs = cross_records(plan, set(letters))
    for r in recs:
        px, py = to_px(r["x"], r["y"])
        g = _glyph_at(meta, px, py)
        r["ch"] = g["ch"] if g else None
        r["below"] = bool(g) and py > meta["baselines"][g["line"]] + 0.02 * FONT_SIZE
        r["part"] = part_of(r["advance"])
    # which glyphs reached the Column lane, which did not
    tagged, untagged = set(), set()
    for r in result.regions:
        c = r.polygon.centroid
        g = _glyph_at(meta, *to_px(c.x, c.y))
        if g is None:
            continue
        (tagged if r.shape_id in letters else untagged).add(g["ch"])
    sewn = {}
    for _b, run in plan.iter_runs():
        sewn.setdefault(run.shape_id, set()).add(run.kind)
    fill_letters = sorted(
        ch for sid, kinds in sewn.items() if sid in letters and "satin" not in kinds
        for ch in [(_glyph_at(meta, *to_px(letters[sid].polygon.centroid.x,
                                           letters[sid].polygon.centroid.y)) or {}).get("ch")]
        if ch)
    classes = {}
    for name, chars, pred in LOWER_CLASSES + UPPER_CLASSES:
        sel = [r for r in recs if r["ch"] and r["ch"] in chars and pred(r["part"], r["below"])]
        classes[name] = summarize(sel, house)
    shorts = {}
    for x, y, _length in junction_short_crosses(plan, set(letters)):
        g = _glyph_at(meta, *to_px(x, y))
        if g:
            shorts[g["ch"]] = shorts.get(g["ch"], 0) + 1
    per_glyph = {}
    for ch in dict.fromkeys(LINES[0] + LINES[1]):
        sel = [r for r in recs if r["ch"] == ch]
        if sel:
            sts = [r["station_lean"] for r in sel if r["station_lean"] is not None]
            per_glyph[ch] = dict(n=len(sel), past45=round(float(np.mean(
                [r["lean"] > 45.0 for r in sel])), 3),
                station_past45=round(float(np.mean([v > 45.0 for v in sts])), 3) if sts else None,
                station_folds=int(sum(v > 45.0 for v in sts)),
                short_at_junction=shorts.get(ch, 0))
    lower = [r for r in recs if r["ch"] and r["ch"].islower()]
    upper = [r for r in recs if r["ch"] and r["ch"].isupper()]
    cap_h = (meta["baselines"][0] - min(g["box"][1] for g in meta["glyphs"] if g["ch"] == "H")) / s
    x_h = (meta["baselines"][1] - min(g["box"][1] for g in meta["glyphs"] if g["ch"] == "x"
                                      or g["ch"] == "u")) / s
    report = dict(width_mm=width_mm, columns=columns, house_deg=house,
                  cap_height_mm=round(cap_h, 2), x_height_mm=round(x_h, 2),
                  stitches=plan.stats.stitch_count, trims=plan.stats.trims,
                  lettering_shapes=len(letters),
                  untagged_glyph_regions=sorted(untagged - tagged),
                  tagged_without_satin=fill_letters,
                  all_lower=summarize(lower, house), all_upper=summarize(upper, house),
                  lower_short_at_junction=sum(v for ch, v in shorts.items() if ch.islower()),
                  upper_short_at_junction=sum(v for ch, v in shorts.items() if ch.isupper()),
                  classes=classes, per_glyph=per_glyph)
    return report, result, plan


