def pair_notes(rb: dict) -> str:
    """Per-arm facts read off the file; the sewn effect is the sew-out's to say."""
    n, t = rb["stitches_by_piece"], rb["trims_by_piece"]
    lines = ["| block | piece | arm | stitches | vs arm 1 | trims | est. minutes |", "|---|---|---|---|---|---|---|"]
    for word, _cut in B_ROWS:
        base = n[f"B:{word}-off"]
        for lbl, _o in B_ARMS:
            v = n[f"B:{word}-{lbl}"]
            lines.append(f"| B | {word} | {lbl} | {v:,} | {'-' if lbl == 'off' else f'{v - base:+,}'} | "
                         f"{t.get(f'B:{word}-{lbl}', 0)} | {sew_minutes(v, t.get(f'B:{word}-{lbl}', 0)):.2f} |")
    base = n["P:off"]
    for lbl, _p in P_ARMS:
        v = n[f"P:{lbl}"]
        lines.append(f"| P | plate + disc | {lbl} | {v:,} | {'-' if lbl == 'off' else f'{v - base:+,}'} | "
                     f"{t.get(f'P:{lbl}', 0)} | {sew_minutes(v, t.get(f'P:{lbl}', 0)):.2f} |")
    return "\n".join(lines) + "\n"


def arm_md5_table(rb: dict) -> str:
    lines = ["| piece | arm | config (what differs) | arm md5 |", "|---|---|---|---|"]
    for word, cut_name in B_ROWS:
        for lbl, ov in B_ARMS:
            cfg = ", ".join(f"{k}={v}" for k, v in ov.items()) or "defaults (switch ON)"
            lines.append(f"| B {word} {B_SIZE[cut_name]:g} mm | {lbl} | `{cfg}` | `{rb['arm_md5'][f'B:{word}-{lbl}']}` |")
    for lbl, p in P_ARMS:
        cfg = f"edge_cap_bean_pitch_mm={p}" if p is not None else "edge_cap_bean_pitch_mm=None (0.73 mm)"
        lines.append(f"| P plate + disc | {lbl} | `{cfg}` | `{rb['arm_md5'][f'P:{lbl}']}` |")
    lines += ["", f"The machine file: `{NAME}.dst`, md5 `{rb['dst_md5']}`, {rb['bytes']:,} bytes."]
    return "\n".join(lines) + "\n"


def cut_notes(cuts: Path) -> str:
    lines = ["", "| cut | width | arm | overrides on the Studio request | whole design | stream md5 |",
             "|---|---|---|---|---|---|"]
    for name in CUTS:
        f = cuts / f"cut_{name}.json"
        if not f.exists():
            continue
        d = json.loads(f.read_text(encoding="utf-8"))
        for label, a in d["arms"].items():
            lines.append(f"| `{name}` | {d['width_mm']:g} mm | {label} | `{a['overrides']}` | "
                         f"{a['stitches_whole']:,} stitches, {a['trims_whole']} trims | `{a['md5'][:8]}` |")
    f = cuts / "cut_p.json"
    if f.exists():
        d = json.loads(f.read_text(encoding="utf-8"))
        lines += ["", "| cut | arm | `edge_cap_bean_pitch_mm` | stitches | trims | cap stations | median cap step |",
                  "|---|---|---|---|---|---|---|"]
        for label, a in d["arms"].items():
            lines.append(f"| `p` | {label} | {a['edge_cap_bean_pitch_mm']} | {a['stitches']:,} | {a['trims']} | "
                         f"{a['cap_points']:,} | {a['cap_median_step_mm']} mm |")
    return "\n".join(lines) + "\n"


def write_docs(out: Path, rb: dict, cuts: Path) -> None:
    text = (README.replace("READBACK", v3.readback_markdown(rb)).replace("PAIRNOTES", pair_notes(rb))
            .replace("ARMMD5", arm_md5_table(rb)).replace("CUTNOTES", cut_notes(cuts))
            .replace("SIZE_MM", f"{rb['extent_mm'][0]} x {rb['extent_mm'][1]}")
            .replace("STITCHES", f"{rb['stitches_file']:,}").replace("TRIMS", str(rb["trims"]))
            .replace("SEWMIN", f"{rb['sew_minutes']:.0f}").replace("TRIM_S", f"{TRIM_S:g}")
            .replace("SPM", str(SPM)).replace("DSTMD5", rb["dst_md5"]))
    (out / "README.md").write_text(text, encoding="utf-8")
    (out / "scoring-sheet.md").write_text(SCORING, encoding="utf-8")


def generate(out: Path, cuts: Path | None = None, renders: Path | None = None, *, quiet: bool = False) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    cuts = cuts or out / "cuts"
    plan, card, extra = build(cuts)
    pattern = plan_to_pattern(plan)
    pattern.metadata("name", "BAYEDGE 40WT")
    path = out / f"{NAME}.dst"
    path.write_bytes(formats.write(pattern, "dst"))
    rb = v2.readback(path, plan, WT, card)
    rb["pieces"] = extra["pieces"]
    rb["block_md5"] = block_digests(plan)
    rb["arm_md5"] = arm_digests(plan)
    rb["trims_by_piece"] = trims_by_piece(plan)
    rb["dst_md5"] = hashlib.md5(path.read_bytes()).hexdigest()
    rb["sew_minutes"] = round(sew_minutes(rb["stitches_file"], rb["trims"]), 1)
    if renders is not None:
        renders.mkdir(parents=True, exist_ok=True)
        v3.render(plan, renders / f"{NAME}.png")
        panel(plan, card, renders / f"{NAME}_block_B.png", rows_B())
        panel(plan, card, renders / f"{NAME}_block_P.png", rows_P())
    if not quiet:
        print(json.dumps({k: v for k, v in rb.items() if k not in
                          ("pieces", "pieces_mm", "stitches_by_piece", "block_md5", "arm_md5", "trims_by_piece")}))
    (out / "readback.json").write_text(json.dumps(rb, indent=1) + "\n", encoding="utf-8")
    write_docs(out, rb, cuts)
    return rb


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--cut", choices=["b81", "b925", "p"], help="digitize this cut's piece and save its arms")
    ap.add_argument("--cuts", default=str(DEFAULT_CUTS))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--renders", default=str(DEFAULT_RENDERS), help="write the PNGs here ('' to skip)")
    args = ap.parse_args(argv)
    if args.cut:
        cut(args.cut, Path(args.cuts))
        return 0
    generate(Path(args.out), Path(args.cuts), Path(args.renders) if args.renders else None)
    return 0


