def _stay_box(p, margin: float = GLYPH_MARGIN_MM) -> tuple[float, float, float, float]:
    """The box of the tagline's STAY: the source glyph outlines between the two bars
    (`bean_glyph_trace.WORD_TEXT['tagline']` = EAT|STAY|PLAY), grown by `margin`."""
    from tools import bean_glyph_trace as bgt
    glyphs = bgt.word_glyphs(p, "tagline")
    labels = bgt.labels_for("tagline", len(glyphs))
    if "|" not in labels:
        raise SystemExit(f"tagline glyph count {len(glyphs)} does not match EAT|STAY|PLAY")
    bars = [i for i, c in enumerate(labels) if c == "|"]
    idx = range(bars[0] + 1, bars[1])
    assert "".join(labels[i] for i in idx) == "STAY", labels
    bs = [glyphs[i].bounds for i in idx]
    return (min(b[0] for b in bs) - margin, min(b[1] for b in bs) - margin,
            max(b[2] for b in bs) + margin, max(b[3] for b in bs) + margin)


def cut_boxes(plan, boxes: dict[str, tuple[float, float, float, float]]) -> dict:
    """Every non-white run lying wholly inside each box, as JSON-able dicts."""
    out = {}
    for key, (gx0, gy0, gx1, gy1) in boxes.items():
        inside, crossing = [], 0
        for b in plan.blocks:
            if min(b.rgb) >= v3.WHITE_MIN:
                continue
            for r in b.runs:
                xs = [q[0] for q in r.points]
                ys = [q[1] for q in r.points]
                if min(xs) >= gx0 and max(xs) <= gx1 and min(ys) >= gy0 and max(ys) <= gy1:
                    inside.append({"kind": r.kind, "jump": bool(r.jump), "trim": bool(r.trim),
                                   "shape_id": r.shape_id, "rgb": [int(v) for v in b.rgb],
                                   "points": [[round(q[0], 4), round(q[1], 4)] for q in r.points]})
                elif max(xs) >= gx0 and min(xs) <= gx1 and max(ys) >= gy0 and min(ys) <= gy1:
                    crossing += 1
        out[key] = {"box_mm": [round(v, 3) for v in (gx0, gy0, gx1, gy1)], "runs": inside,
                    "crossing_runs_dropped": crossing}
    return out


def cut_fremont(name: str, cuts: Path) -> Path:
    """Digitize Fremont once at this cut's width on a Hat (the Studio request, switch pinned ON),
    then PLAN it once per B arm (stage 7 only: `bean_bay_hold._plan`), and save each arm's runs
    inside the cut's boxes."""
    import time
    from tools import bean_bay_hold as bbh
    from tools import fremont_triage as ft
    from tools import small_lettering_compare as slc
    t = time.time()
    width, boxspec = CUTS[name]
    run = ft.run_arm(name, width, None, preflight=False, overrides=dict(SWITCH))
    p = run["gen"].p
    boxes = {}
    for key, (roi, glyphs) in boxspec.items():
        if glyphs == "STAY":
            boxes[key] = _stay_box(p)
        else:
            x0, y0, x1, y1 = ft.roi_mm(p, ft.ROIS[roi])
            boxes[key] = (x0 - CUT_MARGIN_MM, y0 - CUT_MARGIN_MM, x1 + CUT_MARGIN_MM, y1 + CUT_MARGIN_MM)
    out = {"cut": name, "width_mm": width, "garment_id": GARMENT, "base_overrides": SWITCH, "arms": {}}
    for label, ov in B_ARMS:
        pr = bbh._plan(run, ov, ({}, {}))
        plan = pr["plan"]
        out["arms"][label] = {"overrides": {**SWITCH, **ov}, "stitches_whole": plan.stats.stitch_count,
                              "trims_whole": plan.stats.trims, "md5": slc.stream_md5(plan),
                              "boxes": cut_boxes(plan, boxes)}
        print(f"{name}/{label}: {plan.stats.stitch_count:,} st, {plan.stats.trims} tr, "
              f"md5 {out['arms'][label]['md5'][:8]}, "
              + ", ".join(f"{k} {len(v['runs'])} runs ({v['crossing_runs_dropped']} crossing dropped)"
                          for k, v in out["arms"][label]["boxes"].items()), flush=True)
    cuts.mkdir(parents=True, exist_ok=True)
    path = cuts / f"cut_{name}.json"
    path.write_text(json.dumps(out), encoding="utf-8")
    print(f"{name}: {time.time() - t:.0f} s -> {path}", flush=True)
    return path


# --- block P: the synthetic plate ------------------------------------------------------------

P_PPM = 24                  # image px per mm of the synthetic artwork
P_WIDTH_MM = 28.0           # the artwork's width: the Studio width
P_HEIGHT_MM = 12.0
PLATE = (1.0, 1.5, 15.0, 10.5)      # x0, y0, x1, y1 (mm): 14 x 9, bottom-left corner square
PLATE_RADIUS_MM = 3.0               # the top-right corner: the 3 mm curve
DISC_CENTRE_MM = (22.0, 6.0)
DISC_RADIUS_MM = 2.0                # 4 mm across: the small disc


def p_image() -> np.ndarray:
    """BGRA artwork: one dark tatami plate with straight edges, a square corner and an R3 mm
    corner, plus a 4 mm disc, on a transparent ground."""
    W, H = int(P_WIDTH_MM * P_PPM), int(P_HEIGHT_MM * P_PPM)
    img = np.zeros((H, W, 4), np.uint8)
    x0, y0, x1, y1 = PLATE
    r = PLATE_RADIUS_MM
    pts = [(x0, y0), (x1 - r, y0)]
    for a in np.linspace(-90, 0, 40):
        pts.append((x1 - r + r * math.cos(math.radians(a)), y0 + r + r * math.sin(math.radians(a))))
    pts += [(x1, y1), (x0, y1)]
    poly = np.array([[px * P_PPM, py * P_PPM] for px, py in pts], np.int32)
    ink = (30, 30, 30, 255)
    cv2.fillPoly(img, [poly], ink, lineType=cv2.LINE_AA)
    cv2.circle(img, (int(DISC_CENTRE_MM[0] * P_PPM), int(DISC_CENTRE_MM[1] * P_PPM)),
               int(DISC_RADIUS_MM * P_PPM), ink, -1, cv2.LINE_AA)
    return img


def p_config(pitch: float | None) -> PipelineConfig:
    return PipelineConfig(target_width_mm=P_WIDTH_MM, forced_class="flat", thread_wt=WT, garment_id=GARMENT,
                          edge_cap_bean_pitch_mm=pitch)


def cap_stats(plan: StitchPlan) -> dict:
    """The edge cap's own stations: how many, and the median step."""
    caps = [r for _b, r in plan.iter_runs() if r.shape_id == "__edge_cap__"]
    steps = [math.dist(a, b) for r in caps for a, b in zip(r.points, r.points[1:]) if math.dist(a, b) > 1e-9]
    return {"cap_runs": len(caps), "cap_points": sum(len(r.points) for r in caps),
            "cap_median_step_mm": round(statistics.median(steps), 3) if steps else None}


def cut_p(cuts: Path) -> Path:
    img = p_image()
    out = {"cut": "p", "width_mm": P_WIDTH_MM, "garment_id": GARMENT, "forced_class": "flat",
           "plate_mm": list(PLATE), "plate_radius_mm": PLATE_RADIUS_MM,
           "disc_centre_mm": list(DISC_CENTRE_MM), "disc_diameter_mm": 2 * DISC_RADIUS_MM, "arms": {}}
    for label, pitch in P_ARMS:
        _res, plan = digitize(img, p_config(pitch))
        runs = [{"kind": r.kind, "jump": bool(r.jump), "trim": bool(r.trim), "shape_id": r.shape_id,
                 "points": [[round(q[0], 4), round(q[1], 4)] for q in r.points]} for _b, r in plan.iter_runs()]
        out["arms"][label] = {"edge_cap_bean_pitch_mm": pitch, "stitches": plan.stats.stitch_count,
                              "trims": plan.stats.trims, "size_mm": [round(v, 2) for v in plan.stats.size_mm],
                              **cap_stats(plan), "runs": runs}
        print(f"p/{label}: {plan.stats.stitch_count:,} st, {plan.stats.trims} tr, "
              f"{out['arms'][label]['cap_median_step_mm']} mm median cap step", flush=True)
    cuts.mkdir(parents=True, exist_ok=True)
    path = cuts / "cut_p.json"
    path.write_text(json.dumps(out), encoding="utf-8")
    return path


def cut(name: str, cuts: Path) -> Path:
    return cut_p(cuts) if name == "p" else cut_fremont(name, cuts)


# --- the card -----------------------------------------------------------------------------

LETTERS = {**hc.LETTERS, "P": [(0, 4), (0, 0), (2.5, 0), (2.5, 2), (0, 2)]}


class CardBE(v3.CardV3):
    """Card v3's colour stop and digitized-piece rule, with this card's blocks."""

    DIGITIZED = ("B:", "P:")

    def index(self, key: str, x0: float, y0: float, width: float) -> None:
        self.add(0, hc.corners([(x0 + a, y0 + b) for a, b in LETTERS[key]]), f"{key}:index")
        self.add(0, hc.corners([(x0 + 4.5, y0 + 5.0), (x0 + width, y0 + 5.0)]), f"{key}:rule")


def load(cuts: Path, name: str) -> dict:
    return json.loads((cuts / f"cut_{name}.json").read_text(encoding="utf-8"))


def _runs(rows: list[dict]) -> list[StitchRun]:
    return [StitchRun(points=[tuple(p) for p in r["points"]], kind=r["kind"], jump=True, trim=False,
                      shape_id=r["shape_id"]) for r in rows]


def block_B(c: CardBE, x0: float, y0: float, cuts: Path, report: list) -> float:
    """The bay-hold block: a row per word, the three arms side by side (teeth = the arm's number)."""
    c.index("B", x0, y0, 30.0)
    top = y0 + 9.0
    right, bottom = x0, top
    data = {name: load(cuts, name) for name in CUTS}
    for word, cut_name in B_ROWS:
        x = x0
        row_bottom = top
        for k, (label, _ov) in enumerate(B_ARMS, start=1):
            arm = f"{word}-{label}"
            a = data[cut_name]["arms"][label]
            b = a["boxes"][word]
            box = v3.place_runs(c, _runs(b["runs"]), x, top, "B", arm)
            c.add(0, hc.teeth(x, top - 0.8, k), f"B:label:{arm}")
            report.append({"block": "B", "arm": arm, "word": word, "label": label, "cut": cut_name,
                           "size_mm": B_SIZE[cut_name], "overrides": a["overrides"],
                           "cut_stream_md5": a["md5"], "runs": len(b["runs"]),
                           "crossing_runs_dropped": b["crossing_runs_dropped"],
                           "width_mm": round(box[2] - box[0], 2), "height_mm": round(box[3] - box[1], 2)})
            x = max(box[2], x + 4.8) + 4.0          # room for the arm's own teeth
            row_bottom = max(row_bottom, box[3])
        right = max(right, x)
        bottom = row_bottom
        top = row_bottom + 6.5
    c.boxes["B"] = (x0, y0, max(right, x0 + 30.0), bottom)
    return bottom


def block_P(c: CardBE, x0: float, y0: float, cuts: Path, report: list) -> float:
    """The edge-cap block: the four arms in a 2 x 2 grid, teeth = the arm's number."""
    c.index("P", x0, y0, 30.0)
    d = load(cuts, "p")
    top = y0 + 9.0
    gx = 36.0                                      # column pitch: a piece is 29 mm wide
    row_bottom = top
    right = x0
    for k, (label, pitch) in enumerate(P_ARMS, start=1):
        a = d["arms"][label]
        col, row = (k - 1) % 2, (k - 1) // 2
        if col == 0 and row == 1:
            top = row_bottom + 6.5
        x = x0 + col * gx
        box = v3.place_runs(c, _runs(a["runs"]), x, top, "P", label)
        c.add(0, hc.teeth(x, top - 0.8, k), f"P:label:{label}")
        report.append({"block": "P", "arm": label, "label": label, "edge_cap_bean_pitch_mm": pitch,
                       "stitches_cut": a["stitches"], "cap_median_step_mm": a["cap_median_step_mm"],
                       "runs": len(a["runs"]), "width_mm": round(box[2] - box[0], 2),
                       "height_mm": round(box[3] - box[1], 2)})
        row_bottom = max(row_bottom, box[3])
        right = max(right, box[2])
    c.boxes["P"] = (x0, y0, max(right, x0 + 30.0), row_bottom)
    return row_bottom


def build(cuts: Path) -> tuple[StitchPlan, CardBE, dict]:
    c = CardBE(WT)
    report: list[dict] = []
    y = block_B(c, 0.0, 0.0, cuts, report)
    block_P(c, 0.0, y + 5.0, cuts, report)
    plan = c.plan()
    xs = [p[0] for b in plan.blocks for r in b.runs for p in r.points]
    ys = [p[1] for b in plan.blocks for r in b.runs for p in r.points]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    for b in plan.blocks:
        for r in b.runs:
            r.points = [(x - cx, y - cy) for x, y in r.points]
    for table in (c.boxes, c.arms):
        for k, (a, b2, c2, d) in list(table.items()):
            table[k] = (a - cx, b2 - cy, c2 - cx, d - cy)
    plan.design_size_mm = (max(xs) - min(xs), max(ys) - min(ys))
    return plan, c, {"pieces": report, "offset_mm": (round(cx, 3), round(cy, 3))}


def block_digests(plan: StitchPlan) -> dict[str, str]:
    """md5 of each block's stitch output (pieces, labels, index strip of B and P), points
    rounded to 0.001 mm: the test pins these."""
    h: dict[str, "hashlib._Hash"] = {}
    for _b, r in plan.iter_runs():
        key = r.shape_id.split(":")[0]
        m = h.setdefault(key, hashlib.md5())
        m.update(r.shape_id.encode() + b"|" + (b"J" if r.jump else b"-") + (b"T" if r.trim else b"-"))
        m.update(np.round(np.asarray(r.points, float), 3).tobytes())
    return {k: v.hexdigest() for k, v in sorted(h.items())}


def arm_digests(plan: StitchPlan) -> dict[str, str]:
    """md5 per arm (`block:arm`): the arm's own stitches, label excluded, taken from the arm's own
    top-left so WHERE it sits on the card does not count."""
    runs: dict[str, list] = {}
    for _b, r in plan.iter_runs():
        parts = r.shape_id.split(":")
        if len(parts) < 3 or parts[1] in ("label", "strips"):
            continue
        runs.setdefault(":".join(parts[:2]), []).append(np.asarray(r.points, float))
    out = {}
    for k, rs in sorted(runs.items()):
        x0 = min(a[:, 0].min() for a in rs)
        y0 = min(a[:, 1].min() for a in rs)
        m = hashlib.md5()
        for a in rs:
            m.update(np.floor((a - (x0, y0)) * 1000 + 0.5 + 1e-6).astype(np.int64).tobytes())
        out[k] = m.hexdigest()
    return out


def trims_by_piece(plan: StitchPlan) -> dict[str, int]:
    """Trim flags per piece (`block:arm`), counted on the card's own plan (the card re-decides
    every hop with the engine's trim distance)."""
    out: dict[str, int] = {}
    for _b, r in plan.iter_runs():
        parts = r.shape_id.split(":")
        if len(parts) < 3 or parts[1] in ("label", "strips"):
            continue
        out[":".join(parts[:2])] = out.get(":".join(parts[:2]), 0) + (1 if r.trim else 0)
    return dict(sorted(out.items()))


# --- sewing time -----------------------------------------------------------------------------

SPM = 600                   # stitches per minute: an ASSUMPTION for 2-4 mm lettering on a cap
TRIM_S = 6.0                # seconds per trim (cut, hop, lock): an assumption


def sew_minutes(stitches: int, trims: int) -> float:
    return stitches / SPM + trims * TRIM_S / 60.0


# --- renders -----------------------------------------------------------------------------------

def rows_B() -> tuple:
    out = []
    for word, cut_name in B_ROWS:
        names = " | ".join(f"{lbl} ({k})" for k, (lbl, _o) in enumerate(B_ARMS, start=1))
        out.append((f"B {word} at {B_SIZE[cut_name]:g} mm, bean_letter_bay_hold: {names} teeth",
                    tuple(f"B:{word}-{lbl}" for lbl, _o in B_ARMS)))
    return tuple(out)


def rows_P() -> tuple:
    names = " | ".join(f"{lbl} ({k})" for k, (lbl, _p) in enumerate(P_ARMS, start=1))
    keys = tuple(f"P:{lbl}" for lbl, _p in P_ARMS)
    # two rows of two (the card's own 2 x 2): one row of four is 7,000 px wide at 60 px/mm
    return ((f"P edge_cap_bean_pitch_mm: {names} teeth, arms 1-2", keys[:2]), ("P arms 3-4", keys[2:]))


def panel(plan: StitchPlan, card: CardBE, out: Path, rows: tuple, ppm: float = 60.0) -> None:
    saved = v3.ROWS
    v3.ROWS = rows
    try:
        v3.panel(plan, card, out, ppm)
    finally:
        v3.ROWS = saved


