"""results.json (gate_table.py) + ladder.json (ladder_gate.py) -> tables.md.

usage: python make_tables.py RESULTS_JSON LADDER_JSON OUT_MD
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

CASES = [("golden", "golden_tee logo, gradient lane"), ("fremont", "hotel_fremont logo, gradient lane"),
         ("goldensil", "golden_tee layer as a one-ink alpha cutout"),
         ("fremontsil", "hotel_fremont layer as a one-ink alpha cutout"),
         ("becker", "becker_marine_logo.png (no truth)")]
CONFIGS = [("off", "native read OFF"), ("on", "ON (today)"), ("gate3", "ON, floor 3.0")]


def fmt(v, f="%.3f"):
    return "–" if v is None else f % v


def main(res, lad, out):
    rows = json.loads(Path(res).read_text())
    by = {(r["case"], r["rung"], r["config"]): r for r in rows}
    rungs = sorted({r["rung"] for r in rows})
    L = ["# Native edge read by source resolution — tables", "",
         "Generated by `scripts/make_tables.py` from `results.json` and `ladder.json`.", "",
         "Edge error = median distance, stage 4 polygon edge -> native-resolution truth edge, mm "
         "(thread is 0.4 mm). Reversals = vertices turning back more than 120 degrees, per 100 mm "
         "of outline. Bare `vectorize()` on the same masks for every column.", ""]
    for title, key, f in (("Median edge error, mm (lower is better)", "p_med", "%.3f"),
                          ("Reversals per 100 mm (lower is better)", "reversals_per_100mm", "%.1f"),
                          ("Right-angle turns (60-120 deg) per 100 mm — the staircase; square "
                           "corners count too, read the difference", "right_angles_per_100mm", "%.1f"),
                          ("Turning, degrees per mm of outline (lower is smoother)", "turn", "%.1f"),
                          ("Truth edge -> polygon, median mm (recall side)", "r_med", "%.3f"),
                          ("Vertices", "nodes", "%d")):
        L += [f"## {title}", "",
              "| case | px/mm in | " + " | ".join(c[1] for c in CONFIGS) + " |",
              "|---|---|" + "---|" * len(CONFIGS)]
        for case, label in CASES:
            for rung in rungs:
                cells = [by.get((case, rung, c)) for c, _ in CONFIGS]
                if not any(cells):
                    continue
                ppm = next(c for c in cells if c)["input_px_per_mm"]
                L.append(f"| {label} | {ppm:.2f} | " + " | ".join(
                    fmt(c and c[key], f) for c in cells) + " |")
        L.append("")
    # Mean over the four truth cases, per rung.
    L += ["## Mean over the four truth cases", "",
          "| px/mm | " + " | ".join(f"{c[1]} error / reversals" for c in CONFIGS) + " |",
          "|---|" + "---|" * len(CONFIGS)]
    for rung in rungs:
        cells = []
        for c, _ in CONFIGS:
            xs = [by[(k, rung, c)] for k, _ in CASES[:4] if (k, rung, c) in by]
            cells.append(f"{sum(x['p_med'] for x in xs) / len(xs):.3f} mm / "
                         f"{sum(x['reversals_per_100mm'] for x in xs) / len(xs):.1f}")
        L.append(f"| {rung:g} | " + " | ".join(cells) + " |")
    L.append("")
    # The ladder: analytic truth, synthetic art.
    lrows = json.loads(Path(lad).read_text())
    g = defaultdict(dict)
    for r in lrows:
        if r["produced"]:
            g[(r["fixture"], r["shape"], r["nominal"])][r["config"]] = r
    L += ["## `tools/edge_truth_ladder.py` — synthetic art, analytic truth", "",
          "RMS distance to the analytic edge, mm (hausdorff in brackets). `logo_whitebg` and "
          "`ribbon_curve` at the 200 / 400 / 600 px rungs, read at the width that gives 1.8 / 3 / 5 "
          "px/mm. Flat lane.", "",
          "| shape | px/mm | " + " | ".join(c[1] for c in CONFIGS) + " |",
          "|---|---|" + "---|" * len(CONFIGS)]
    for (fx, shape, nom), cs in g.items():
        L.append(f"| {fx} {shape} | {nom:g} | " + " | ".join(
            (f"{cs[c]['rms_mm']:.3f} ({cs[c]['hausdorff_mm']:.2f})" if c in cs else "–")
            for c, _ in CONFIGS) + " |")
    L.append("")
    Path(out).write_text("\n".join(L), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main(*sys.argv[1:])
