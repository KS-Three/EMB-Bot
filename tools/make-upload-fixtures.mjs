// Generate the two synthetic upload fixtures the full-resolution upload specs
// need (W5-08). Neither is client art; both are rebuilt from files already in
// the repo, so `node tools/make-upload-fixtures.mjs` reproduces them.
//
//   app/e2e/fixtures/small_text_logo.svg
//       Small lettering as PATHS (no <text>, so the render never depends on an
//       installed font), outlined from the shipped Ink/Stitch Medium Font
//       (src/fonts/medium_font.json, SIL OFL 1.1 -- its license text is
//       src/fonts/medium_font.LICENSE.txt), inside a plain frame. Three text
//       sizes, 16 / 22 / 34 viewBox units of cap height: 2.7 / 3.7 / 5.7 mm
//       when the logo is sewn 100 mm wide, which is the band where the
//       1,200-px preview and the 2,800-px render part ways.
//
//   app/e2e/fixtures/rotated_exif6.jpg      (2,520 x 1,400 upright, stored 1,400 x 2,520)
//   app/e2e/fixtures/rotated_exif1_twin.jpg (the same art upright, no rotation tag)
//       A phone-style JPEG: the pixels are stored sideways and EXIF
//       orientation 6 ("rotate 90 degrees clockwise to display") puts them
//       upright, so a browser shows trace-holes-and-colors.png (an existing,
//       non-client e2e fixture, scaled 14x) and cv2.imdecode would show it on
//       its side. The twin is the same picture stored upright: it is what a
//       correct ON render of the rotated file must equal.
//
// The JPEGs are encoded by Chromium's canvas (Playwright, from app/node_modules
// -- run `npm install` in app/ first), because the repo has no JPEG encoder;
// the EXIF segment is spliced in here by hand.
import "./_help.mjs";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURES = path.join(ROOT, "app", "e2e", "fixtures");

// ---- the SVG ---------------------------------------------------------------

const f1 = (n) => String(Math.round(n * 10) / 10);

// Signed area (shoelace); the rails of a satin column can run either way, and
// a path drawn with `nonzero` unions only same-wound pieces.
function area(ring) {
  let a = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1, y1] = ring[i], [x2, y2] = ring[(i + 1) % ring.length];
    a += x1 * y2 - x2 * y1;
  }
  return a / 2;
}

// A glyph's satin columns as outlines: rail A forward, rail B back. Every
// outline is wound the same way so the columns of one letter union cleanly.
function glyphRings(glyph) {
  const rings = [];
  for (const col of glyph.cols || []) {
    const ring = [...col.railA, ...[...col.railB].reverse()];
    if (ring.length >= 3) rings.push(area(ring) < 0 ? ring.reverse() : ring);
  }
  return rings;
}

// Lay `text` out in `font`, scaled so a capital H is `capUnits` tall, with the
// left edge at x0 and the baseline at y0. Font y already grows downward, as
// SVG's does (measured: a flipped first draft set the text upside down), so
// the baseline is the glyph's LARGEST y.
export function textPath(font, text, { x0, y0, capUnits, weight = 0 }) {
  const ys = (font.glyphs.H.cols || []).flatMap((c) => [...c.railA, ...c.railB].map((p) => p[1]));
  const capFont = Math.max(...ys) - Math.min(...ys);
  const base = Math.max(...ys);
  const s = capUnits / capFont;
  let pen = x0;
  const d = [];
  for (const ch of text) {
    if (ch === " ") { pen += (font.advSpace || font.advDefault) * s; continue; }
    const g = font.glyphs[ch];
    if (!g) throw new Error(`medium_font has no glyph for ${JSON.stringify(ch)}`);
    for (const ring of glyphRings(g)) {
      d.push("M" + ring.map(([x, y]) => `${f1(pen + x * s)} ${f1(y0 + (y - base) * s)}`).join("L") + "Z");
    }
    pen += (g.adv || font.advDefault) * s;
  }
  return { d: d.join(""), width: pen - x0 };
}

export function buildSvg(font) {
  const W = 600, H = 300;
  const lines = [
    { text: "SMALL TEXT", capUnits: 34, y0: 112, color: "#0b2a5b" },
    { text: "NOT A CLIENT LOGO", capUnits: 22, y0: 170, color: "#a3112a" },
    { text: "ABC 0123456789", capUnits: 16, y0: 220, color: "#0b2a5b" },
  ];
  const out = [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}">`,
    `  <!-- Synthetic upload fixture, generated by tools/make-upload-fixtures.mjs.`,
    `       Lettering outlined from the Ink/Stitch Medium Font (SIL OFL 1.1, src/fonts/medium_font.LICENSE.txt). -->`,
    `  <rect x="0" y="0" width="${W}" height="${H}" fill="#ffffff"/>`,
    `  <path fill="#0b2a5b" fill-rule="evenodd" d="M12 12H588V288H12ZM22 22V278H578V22Z"/>`,
  ];
  for (const ln of lines) {
    const probe = textPath(font, ln.text, { x0: 0, y0: ln.y0, capUnits: ln.capUnits });
    const x0 = (W - probe.width) / 2;
    const { d } = textPath(font, ln.text, { x0, y0: ln.y0, capUnits: ln.capUnits });
    out.push(`  <path fill="${ln.color}" stroke="${ln.color}" stroke-width="${f1(ln.capUnits * 0.07)}" stroke-linejoin="round" d="${d}"/>`);
  }
  out.push("</svg>", "");
  return out.join("\n");
}

// ---- the JPEGs -------------------------------------------------------------

// APP1 "Exif" segment holding one IFD0 entry, Orientation (0x0112) = `orient`,
// little-endian. Spliced after the SOI (and after a JFIF APP0 when present, as
// the spec wants APP0 first).
export function exifSegment(orient) {
  const tiff = Buffer.alloc(8 + 2 + 12 + 4);
  tiff.write("II", 0, "latin1");
  tiff.writeUInt16LE(42, 2);
  tiff.writeUInt32LE(8, 4);                 // IFD0 offset
  tiff.writeUInt16LE(1, 8);                 // one entry
  tiff.writeUInt16LE(0x0112, 10);           // Orientation
  tiff.writeUInt16LE(3, 12);                // SHORT
  tiff.writeUInt32LE(1, 14);                // count
  tiff.writeUInt16LE(orient, 18);           // value
  const body = Buffer.concat([Buffer.from("Exif\0\0", "latin1"), tiff]);
  const head = Buffer.from([0xff, 0xe1, 0, 0]);
  head.writeUInt16BE(body.length + 2, 2);
  return Buffer.concat([head, body]);
}

export function withOrientation(jpeg, orient) {
  if (jpeg[0] !== 0xff || jpeg[1] !== 0xd8) throw new Error("not a JPEG");
  let at = 2;
  if (jpeg[2] === 0xff && jpeg[3] === 0xe0) at = 4 + jpeg.readUInt16BE(4);   // keep JFIF first
  return Buffer.concat([jpeg.subarray(0, at), exifSegment(orient), jpeg.subarray(at)]);
}

// Upright art -> { upright, sideways } JPEG bytes, as Chromium's canvas encodes
// them. `sideways` is the art rotated 90 degrees counter-clockwise, which is
// what orientation 6 undoes. `scale` is nearest-neighbour: the art is flat
// colour, and crisp edges keep the two JPEGs' blocks comparable.
async function encodeJpegs(pngPath, scale, quality) {
  const require = createRequire(path.join(ROOT, "app", "package.json"));
  const { chromium } = require("playwright");
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    const b64 = readFileSync(pngPath).toString("base64");
    const out = await page.evaluate(async ({ b64, scale, quality }) => {
      const img = new Image();
      await new Promise((res, rej) => { img.onload = res; img.onerror = rej; img.src = "data:image/png;base64," + b64; });
      const W = img.width * scale, H = img.height * scale;
      const up = document.createElement("canvas");
      up.width = W; up.height = H;
      const u = up.getContext("2d");
      u.imageSmoothingEnabled = false;
      u.drawImage(img, 0, 0, W, H);
      const side = document.createElement("canvas");
      side.width = H; side.height = W;
      const s = side.getContext("2d");
      s.translate(0, W);            // counter-clockwise quarter turn
      s.rotate(-Math.PI / 2);
      s.drawImage(up, 0, 0);
      const enc = async (cv) => {
        const blob = await new Promise((r) => cv.toBlob(r, "image/jpeg", quality));
        const bytes = new Uint8Array(await blob.arrayBuffer());
        let bin = "";
        for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
        return btoa(bin);
      };
      return { upright: await enc(up), sideways: await enc(side), W, H };
    }, { b64, scale, quality });
    return { upright: Buffer.from(out.upright, "base64"), sideways: Buffer.from(out.sideways, "base64"), W: out.W, H: out.H };
  } finally {
    await browser.close();
  }
}

async function main() {
  const font = JSON.parse(readFileSync(path.join(ROOT, "src", "fonts", "medium_font.json"), "utf8"));
  const svgPath = path.join(FIXTURES, "small_text_logo.svg");
  writeFileSync(svgPath, buildSvg(font));
  console.log("wrote " + path.relative(ROOT, svgPath));

  const { upright, sideways, W, H } = await encodeJpegs(path.join(FIXTURES, "trace-holes-and-colors.png"), 14, 0.95);
  const rotated = withOrientation(sideways, 6);
  writeFileSync(path.join(FIXTURES, "rotated_exif6.jpg"), rotated);
  writeFileSync(path.join(FIXTURES, "rotated_exif1_twin.jpg"), upright);
  console.log(`wrote rotated_exif6.jpg (stored ${H} x ${W}, ${rotated.length} bytes) and rotated_exif1_twin.jpg (${W} x ${H}, ${upright.length} bytes)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
